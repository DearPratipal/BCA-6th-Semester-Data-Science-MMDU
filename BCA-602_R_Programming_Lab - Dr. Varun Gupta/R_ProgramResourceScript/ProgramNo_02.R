# Program to perform arithmetic operations on two numbers

# Assign values to variables
a <- 10
b <- 5

# Arithmetic operations
sum <- a + b
difference <- a - b
product <- a * b
division <- a / b

# Display results
cat("Sum =", sum, "\n")
cat("Difference =", difference, "\n")
cat("Product =", product, "\n")
cat("Division =", division, "\n")

